import { webConfiguration } from "../../lib/config";

export const dynamic = "force-dynamic";

export function GET() {
  try {
    webConfiguration();
    return Response.json(
      { status: "ok" },
      { headers: { "Cache-Control": "no-store" } },
    );
  } catch {
    return Response.json(
      { status: "unavailable" },
      { status: 503, headers: { "Cache-Control": "no-store" } },
    );
  }
}
